import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
export const hash = data => createHash("sha256").update(data).digest("hex");
export function stableId(key) {
  const bytes = createHash("sha256").update(key).digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 15) | 80;
  bytes[8] = (bytes[8] & 63) | 128;
  const hex = bytes.toString("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
export const quote = value => `'${String(value).replaceAll("'", "''")}'`;

export function buildMoonImport(manifest) {
  const collection = { ...manifest.collection, id: stableId(`nodeine:collection:${manifest.collection.key}`) };
  const keys = new Set(), sources = new Set(), pixels = new Set(), drives = new Set();
  const items = [], threads = [];
  for (const group of manifest.groups) {
    if (keys.has(group.key) || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(group.key)) throw Error("Invalid or repeated group key");
    keys.add(group.key);
    if (group.items.length < 2 || group.items.length > 12) throw Error("A group needs 2–12 images");
    const thread = {
      id: stableId(`nodeine:thread:${collection.key}:${group.key}`),
      slug: `${collection.key}-${group.key}`,
      title: `${group.title} — composition & details`,
      summary: group.note,
      items: /** @type {Array<{artworkId: string, position: number, relation: string, note: string}>} */ ([]),
    };
    if (thread.title.length > 80 || thread.slug.length > 96 || thread.summary.length > 500) throw Error("Thread text exceeds limits");
    for (const [position, source] of group.items.entries()) {
      if (!/^[a-f0-9]{64}$/.test(source.sha256) || !/^[a-f0-9]{64}$/.test(source.pixelSha256)) throw Error("Missing source fingerprints");
      if (sources.has(source.sha256) || pixels.has(source.pixelSha256) || drives.has(source.driveId)) throw Error("Unreviewed duplicate source");
      sources.add(source.sha256); pixels.add(source.pixelSha256); drives.add(source.driveId);
      if (path.basename(source.sourceName) !== source.sourceName) throw Error("Source must be a filename");
      if (position === 0 && source.role !== "Full composition") throw Error("Composition must come before details");
      const sequence = items.length + 1;
      const number = String(sequence).padStart(3, "0");
      const item = {
        ...source,
        id: stableId(`nodeine:artwork:${collection.key}:${source.sha256}`),
        title: position === 0 ? group.title : `${group.title} — ${source.role}`,
        description: `${source.role} in ${collection.title}. ${group.note}`,
        src: `/art/${collection.prefix}-${number}.webp`,
        thumbSrc: `/thumbs/${collection.prefix}-${number}.webp`,
        sortOrder: sequence,
        tags: [...collection.tags, `moon-study-${group.key}`, position === 0 ? "full-composition" : "detail-study"],
      };
      items.push(item);
      thread.items.push({ artworkId: item.id, position: position + 1, relation: position === 0 ? "origin" : "composition", note: `${source.role}. Curated related study in ${group.title}; not an assertion of an exact pixel crop.` });
    }
    threads.push(thread);
  }
  return { collection, items, threads };
}

export function moonSql(manifest, model) {
  const { collection: c, items, threads } = model;
  const q = quote;
  return `-- Generated by scripts/process-nodeine-moon-import.mjs from the reviewed manifest.
-- Additive content only. No schema, grants, auth, messages or existing worlds changed.
-- Publish the matching web assets first. Reruns do not overwrite owner edits.
begin;
do $$ begin
  if not exists (select 1 from public.profiles where id=${q(manifest.ownerId)}) then raise exception 'Expected owner is missing'; end if;
  if exists (select 1 from public.collections where (slug=${q(c.key)} and id<>${q(c.id)}) or (id=${q(c.id)} and owner_id<>${q(manifest.ownerId)})) then raise exception 'World identity collision'; end if;
end $$;
insert into public.collections (id,owner_id,title,slug,summary,world_code,sort_order)
values (${q(c.id)},${q(manifest.ownerId)},${q(c.title)},${q(c.key)},${q(c.summary)},${q(c.worldCode)},${c.sortOrder})
on conflict (id) do nothing;

${items.map(i => `insert into public.artworks (id,collection_id,title,src,thumb_src,media_type,mood,tags,sort_order)
values (${q(i.id)},${q(c.id)},${q(i.title)},${q(i.src)},${q(i.thumbSrc)},'image',${q(c.mood)},array[${i.tags.map(q).join(",")} ]::text[],${i.sortOrder})
on conflict (id) do nothing;`).join("\n")}

do $$ begin
  if (select count(*) from public.artworks where collection_id=${q(c.id)} and id in (${items.map(i=>q(i.id)).join(",")})) <> ${items.length} then raise exception 'Artwork identity collision'; end if;
end $$;

${threads.map(t => `do $$ begin
  if exists(select 1 from public.world_threads where (slug=${q(t.slug)} and id<>${q(t.id)}) or (id=${q(t.id)} and owner_id<>${q(manifest.ownerId)})) then raise exception 'Thread identity collision'; end if;
  if not exists(select 1 from public.world_threads where id=${q(t.id)}) then
    insert into public.world_threads (id,owner_id,title,slug,summary,visibility,allow_forks)
    values (${q(t.id)},${q(manifest.ownerId)},${q(t.title)},${q(t.slug)},${q(t.summary)},'public',false);
    insert into public.world_thread_items (thread_id,artwork_id,position,relation_type,note,added_by) values
    ${t.items.map(i=>`(${q(t.id)},${q(i.artworkId)},${i.position},${q(i.relation)},${q(i.note)},${q(manifest.ownerId)})`).join(",\n    ")};
  end if;
end $$;`).join("\n")}
set constraints all immediate;
commit;
`;
}

async function writeNewAsset(destination, data) {
  try { await writeFile(destination, data, { flag: "wx" }); }
  catch (error) {
    if (error.code !== "EEXIST") throw error;
    if (hash(await readFile(destination)) !== hash(data)) throw Error(`Refusing to overwrite different asset: ${destination}`);
  }
}

async function main() {
  const sourceDirectory = process.argv[2];
  if (!sourceDirectory) throw Error("Usage: node scripts/process-nodeine-moon-import.mjs /path/to/originals");
  const manifest = JSON.parse(await readFile(path.join(root, "scripts/nodeine-moon-manifest.json"), "utf8"));
  const model = buildMoonImport(manifest);
  // Validate the complete batch before creating a single published asset.
  for (const item of model.items) {
    const source = await readFile(path.join(sourceDirectory, item.sourceName));
    if (source.length !== item.size || hash(source) !== item.sha256) throw Error(`Source changed or incomplete: ${item.sourceName}`);
    const pixels = await sharp(source).rotate().ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const fingerprint = createHash("sha256").update(JSON.stringify(pixels.info)).update(pixels.data).digest("hex");
    if (fingerprint !== item.pixelSha256) throw Error(`Pixel fingerprint changed: ${item.sourceName}`);
  }
  const outputs = [];
  for (const item of model.items) {
    const original = path.join(sourceDirectory, item.sourceName);
    const art = await sharp(original).rotate().resize({ width: 2000, height: 2400, fit: "inside", withoutEnlargement: true }).webp({ quality: 90, effort: 5 }).toBuffer();
    // Preserve the complete composition, including inscriptions and diptychs.
    const thumb = await sharp(original).rotate().resize({ width: 640, height: 800, fit: "inside", withoutEnlargement: true }).webp({ quality: 82, effort: 5 }).toBuffer();
    await writeNewAsset(path.join(root, "public", item.src), art);
    await writeNewAsset(path.join(root, "public", item.thumbSrc), thumb);
    outputs.push({ id: item.id, src: item.src, sha256: hash(art), bytes: art.length, thumbSrc: item.thumbSrc, thumbSha256: hash(thumb), thumbBytes: thumb.length });
  }
  await writeFile(path.join(root, "supabase/import-september-2026-aspects-of-the-moon.sql"), moonSql(manifest, model));
  const fallback = model.items.map(i=>({ id:i.id, title:i.title, type:"image", src:i.src, thumbSrc:i.thumbSrc, series:model.collection.title, category:model.collection.category, mood:model.collection.mood, model:"AI Generated", description:i.description, tags:i.tags }));
  await writeFile(path.join(root, "lib/moon-fallback-world.ts"), `// Generated from the reviewed Aspects of the Moon manifest.\nimport type { ImportedFallbackItem } from "./imported-fallback-worlds";\n\nexport const moonFallbackItems: ImportedFallbackItem[] = ${JSON.stringify(fallback,null,2)};\n`);
  await writeFile(path.join(root, "scripts/nodeine-moon-assets.json"), JSON.stringify(outputs,null,2)+"\n");
  console.log(JSON.stringify({ world:model.collection.id, artworks:model.items.length, pairedThreads:model.threads.length, optimizedBytes:outputs.reduce((n,i)=>n+i.bytes+i.thumbBytes,0) },null,2));
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  main().catch(error => { console.error(error); process.exitCode = 1; });
}
